// Writes the reference yields the app ships, from the bulletin as re-read.
//
//   node research/mab37/to-app.mjs            write app/src/data/mab37_yields.js
//   node research/mab37/to-app.mjs --check    exit 1 if that file is out of date
//
// Every conversion is a row of mab37.json, under the starting form and product the bulletin prints
// it under, with the bulletin's average and range. Nothing is worked out: a row the bulletin gives
// only a range for has `yield: null`. app-species.json says which tables a species uses and
// cautions.json holds the note shown beside a value that looks wrong in the bulletin itself.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUTPUT = join(HERE, '..', '..', 'app', 'src', 'data', 'mab37_yields.js');
const read = (name) => JSON.parse(readFileSync(join(HERE, name), 'utf8'));
const tableOf = (r) => [r.group, r.species, r.subheading].filter(Boolean).join(' / ');
const ARROW = ' → ';

export function buildYields({ dataset = read('mab37.json'), species = read('app-species.json').species, cautions = read('cautions.json').cautions } = {}) {
  const problems = [];
  const tables = new Map();
  for (const row of dataset.rows) {
    const key = tableOf(row);
    if (!tables.has(key)) tables.set(key, []);
    tables.get(key).push(row);
  }
  const notes = new Map((dataset.notes ?? []).map((n) => [n.applies_to, n.text]));
  const known = new Set(dataset.rows.map((r) => r.id));
  for (const id of Object.keys(cautions)) if (!known.has(id)) problems.push(`cautions.json: no row ${id} in mab37.json`);

  const usedCautions = new Set();
  const out = {};
  for (const s of species) {
    if (out[s.name]) problems.push(`${s.name}: listed twice in app-species.json`);
    if (!s.tables?.length) problems.push(`${s.name}: no table`);
    const conversions = {};
    for (const t of s.tables ?? []) {
      const rows = tables.get(t.table);
      if (!rows) { problems.push(`${s.name}: no table "${t.table}" in mab37.json`); continue; }
      for (const row of rows) {
        const from = `${row.from}${t.from_suffix ?? ''}`;
        const key = `${from}${ARROW}${row.to}`;
        if (row.from.includes(ARROW) || row.to.includes(ARROW)) problems.push(`${row.id}: a form name contains the arrow`);
        if (conversions[key]) problems.push(`${s.name}: "${key}" comes from both ${conversions[key].row} and ${row.id}`);
        const note = notes.get(row.group) ?? null;
        if (cautions[row.id]) usedCautions.add(row.id);
        conversions[key] = {
          yield: row.average,
          range: row.range,
          row: row.id,
          ...(note ? { note } : {}),
          ...(cautions[row.id] ? { caution: cautions[row.id] } : {}),
        };
      }
    }
    out[s.name] = { scientific_name: s.scientific_name, category: s.category, conversions };
  }
  for (const id of Object.keys(cautions)) if (known.has(id) && !usedCautions.has(id)) problems.push(`cautions.json: row ${id} is in no table the app uses`);
  return { yields: out, problems };
}

const q = (s) => JSON.stringify(s);
export function render(yields) {
  const lines = [
    '// Reference yields from "Recoveries and Yields from Pacific Fish and Shellfish" (Alaska Sea Grant',
    '// Marine Advisory Bulletin 37, revised 2004), row for row as the bulletin prints them.',
    '//',
    '// GENERATED by research/mab37/to-app.mjs from research/mab37/mab37.json. Do not edit this file:',
    '// correct the page file the row comes from (after looking at the scan), or app-species.json or',
    '// cautions.json, and run `node research/mab37/to-app.mjs`. A test fails if this file is stale.',
    '//',
    '// yield   the bulletin\'s average, as a percentage of the starting form\'s weight; null where it',
    '//         prints only a range',
    '// range   the bulletin\'s range, or null',
    '// row     the row in mab37.json: p09R-21 is PDF page 9, right-hand printed page, row 21',
    '// note    a note the bulletin itself prints for that table',
    '// caution why a value that is printed clearly still looks wrong',
    '',
    'export const MAB37_YIELDS = {',
  ];
  for (const [name, s] of Object.entries(yields)) {
    lines.push(`  ${q(name)}: {`, `    scientific_name: ${q(s.scientific_name)},`, `    category: ${q(s.category)},`, '    conversions: {');
    for (const [key, c] of Object.entries(s.conversions)) {
      const parts = [`yield: ${c.yield === null ? 'null' : c.yield}`, `range: ${c.range ? `[${c.range[0]}, ${c.range[1]}]` : 'null'}`, `row: ${q(c.row)}`];
      if (c.note) parts.push(`note: ${q(c.note)}`);
      if (c.caution) parts.push(`caution: ${q(c.caution)}`);
      lines.push(`      ${q(key)}: { ${parts.join(', ')} },`);
    }
    lines.push('    },', '  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

function main() {
  const { yields, problems } = buildYields();
  if (problems.length) { console.error(`${problems.join('\n')}\n\n${problems.length} problem(s). Nothing written.`); process.exit(1); }
  const text = render(yields);
  const count = Object.values(yields).reduce((n, s) => n + Object.keys(s.conversions).length, 0);
  if (process.argv.includes('--check')) {
    let current = null;
    try { current = readFileSync(OUTPUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== text) { console.error('app/src/data/mab37_yields.js is out of date. Run: node research/mab37/to-app.mjs'); process.exit(1); }
    console.log(`Up to date: ${Object.keys(yields).length} species, ${count} conversions.`);
    return;
  }
  writeFileSync(OUTPUT, text);
  console.log(`${Object.keys(yields).length} species, ${count} conversions written to app/src/data/mab37_yields.js.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
